print('\n════ 6. 旺相休囚死(午月:火令) ════')
def wx(month_dz):
    map_ = {'寅':'木','卯':'木','辰':'土','巳':'火','午':'火','未':'土','申':'金','酉':'金','戌':'土','亥':'水','子':'水','丑':'土'}
    order = ['木','火','土','金','水']; w = map_[month_dz]
    st = {}
    for x in order:
        if x==w: s='旺'
        elif order[(order.index(w)+1)%5]==x: s='相'
        elif order[(order.index(w)+4)%5]==x: s='休'
        elif order[(order.index(w)+3)%5]==x: s='囚'
        else: s='死'
        st[x]=s
    return st
st = wx('午')
check('旺相', '午月土=相(记忆:土为相被火生)', st['土']=='相', f'土:{st["土"]} 火:{st["火"]} 木:{st["木"]} 水:{st["水"]} 金:{st["金"]}')

